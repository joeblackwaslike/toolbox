import { type ToolUsage, type UsageOption, usageOf } from '../cli.ts';
import type { ToolManifest } from '../manifest.ts';
import { compareText } from './files.ts';

const SHELLS = ['zsh', 'bash', 'fish'] as const;

function flagCell(option: UsageOption): string {
  const short = option.short === null ? '' : `-${option.short}, `;
  const value = option.type === 'bool' ? '' : ` <${option.long}>`;
  return `\`${short}--${option.long}${value}\``;
}

function defaultCell(option: UsageOption): string {
  return option.default === null ? '' : `\`${String(option.default)}\``;
}

function escapeCell(text: string): string {
  return text.replaceAll('|', String.raw`\|`);
}

function argumentsSection(usage: ToolUsage): string[] {
  if (usage.args.length === 0) return [];
  const rows = usage.args.map(
    (arg) => `| \`${arg.name}\` | ${arg.required ? 'yes' : 'no'} | ${escapeCell(arg.summary)} |`,
  );
  return [
    '## Arguments',
    '',
    '| Name | Required | Description |',
    '| --- | --- | --- |',
    ...rows,
    '',
  ];
}

function optionsSection(usage: ToolUsage): string[] {
  const rows = usage.options.map(
    (option) =>
      `| ${flagCell(option)} | ${option.type} | ${defaultCell(option)} | ${escapeCell(option.summary)} |`,
  );
  return [
    '## Options',
    '',
    '| Flag | Type | Default | Description |',
    '| --- | --- | --- | --- |',
    ...rows,
    '',
  ];
}

/** Extra facts about the tool directory that change its README. */
export interface ReadmeOptions {
  /** True when `tools/<name>/docs/guide.md` exists; the README then links it. */
  hasGuide?: boolean;
}

/**
 * Renders `tools/<name>/README.md` from a manifest: usage line, arguments and options (the
 * manifest's own, then the built-in flags), and the completion files. Output is deterministic.
 */
export function renderToolReadme(m: ToolManifest, options: ReadmeOptions = {}): string {
  const usage = usageOf(m);
  const facts = [
    `Version ${m.version}.`,
    `Language ${m.language}.`,
    `Platforms ${m.platforms.join(', ')}.`,
    ...(m.alias === undefined ? [] : [`Alias \`${m.alias}\`.`]),
  ];
  return [
    `# ${m.name}`,
    '',
    '<!-- Generated by `tbx gen` from tool.toml. Do not edit. -->',
    '',
    m.summary,
    '',
    facts.join(' '),
    '',
    '## Usage',
    '',
    '```',
    usage.usage,
    '```',
    '',
    ...argumentsSection(usage),
    ...optionsSection(usage),
    ...(options.hasGuide === true ? ['## Guide', '', '[docs/guide.md](docs/guide.md)', ''] : []),
    '## Completions',
    '',
    ...SHELLS.map((shell) => `- ${shell}: \`completions/${m.name}.${shell}\``),
    '',
  ].join('\n');
}

/** Renders `docs/catalog.md`: one table row per tool, sorted by name. */
export function renderCatalog(ms: ToolManifest[]): string {
  const rows = [...ms]
    .sort((a, b) => compareText(a.name, b.name))
    .map((m) => {
      const alias = m.alias === undefined ? '' : `\`${m.alias}\``;
      return `| \`${m.name}\` | ${alias} | ${m.language} | ${m.version} | ${escapeCell(m.summary)} |`;
    });
  return [
    '# Tool catalog',
    '',
    '<!-- Generated by `tbx gen` from tool.toml. Do not edit. -->',
    '',
    '| Tool | Alias | Language | Version | Summary |',
    '| --- | --- | --- | --- | --- |',
    ...rows,
    '',
  ].join('\n');
}
